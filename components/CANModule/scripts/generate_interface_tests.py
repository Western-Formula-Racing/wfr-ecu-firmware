import re
from pathlib import Path


BO_PATTERN = re.compile(r"^BO_\s+(\d+)\s+([A-Za-z0-9_]+):\s+(\d+)\s+([A-Za-z0-9_]+)")


def sanitize_name(name: str) -> str:
    name = re.sub(r'[^a-zA-Z0-9]', '_', name)
    name = re.sub(r'_+', '_', name)
    name = name.strip('_')
    if re.match(r'^\d', name):
        name = "_" + name
    return name.upper()


def to_struct_name(name: str) -> str:
    parts = re.split(r'[^a-zA-Z0-9]+', name)
    parts = [p for p in parts if p]
    base = "".join(part[:1].upper() + part[1:] for part in parts)
    return base if base.endswith("Message") else base + "Message"


def to_cache_field_name(message_name: str) -> str:
    parts = re.split(r'[^a-zA-Z0-9]+', message_name)
    parts = [p for p in parts if p]
    if not parts:
        return "unknownMessage"
    first = parts[0][:1].lower() + parts[0][1:]
    rest = [p[:1].upper() + p[1:] for p in parts[1:]]
    return first + "".join(rest)


def parse_dbc_messages(dbc_path: Path) -> list[dict]:
    messages = []
    with dbc_path.open("r", encoding="utf-8") as f:
        for raw_line in f:
            line = raw_line.strip()
            match = BO_PATTERN.match(line)
            if not match:
                continue
            messages.append({
                "can_id": int(match.group(1)),
                "name": match.group(2),
                "dlc": int(match.group(3)),
                "sender": match.group(4),
            })
    return messages


def should_skip_message(message: dict) -> bool:
    return (
        message["name"] == "VECTOR__INDEPENDENT_SIG_MSG"
        or message["sender"] == "Vector__XXX"
    )


def load_ownership_config(config_path: Path) -> dict:
    import yaml
    with config_path.open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def resolve_owner(message: dict, ownership_config: dict) -> str:
    overrides = ownership_config.get("overrides", {})
    node_map = ownership_config.get("node_map", {})

    if message["name"] in overrides:
        return overrides[message["name"]]

    sender = message["sender"]
    if sender not in node_map:
        return "MODULE_UNKNOWN"

    return node_map[sender]


def generate_interface_test_cpp(messages: list[dict], ownership_config: dict, output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)

    usable = [m for m in messages if not should_skip_message(m)]

    lines = []
    lines.append("// AUTO-GENERATED FILE. DO NOT EDIT.")
    lines.append("// Generated by scripts/generate_interface_tests.py")
    lines.append("")
    lines.append("#include <cassert>")
    lines.append("#include <cstdint>")
    lines.append("#include <cstring>")
    lines.append("#include <deque>")
    lines.append("#include <iostream>")
    lines.append("")
    lines.append('#include "can/CanInterface.hpp"')
    lines.append('#include "can/CanError.hpp"')
    lines.append('#include "can/CanFrame.hpp"')
    lines.append('#include "can/ICanDriver.hpp"')
    lines.append('#include "can/ICanMutex.hpp"')
    lines.append('#include "can_gen/CanCodec.hpp"')
    lines.append('#include "can_gen/CanMessages.hpp"')
    lines.append('#include "can_gen/CanRegistry.hpp"')
    lines.append('#include "can_gen/CanStateCache.hpp"')
    lines.append("")
    lines.append("class MockCanDriver : public ICanDriver {")
    lines.append("public:")
    lines.append("    bool transmit(const CanFrame& frame) override {")
    lines.append("        lastTransmitted = frame;")
    lines.append("        transmitCalled = true;")
    lines.append("        return transmitResult;")
    lines.append("    }")
    lines.append("")
    lines.append("    bool receive(CanFrame& frame, uint32_t /*timeoutMs*/) override {")
    lines.append("        if (rxQueue.empty()) {")
    lines.append("            return false;")
    lines.append("        }")
    lines.append("        frame = rxQueue.front();")
    lines.append("        rxQueue.pop_front();")
    lines.append("        receiveCalled = true;")
    lines.append("        return true;")
    lines.append("    }")
    lines.append("")
    lines.append("    void inject(const CanFrame& frame) {")
    lines.append("        rxQueue.push_back(frame);")
    lines.append("    }")
    lines.append("")
    lines.append("    void reset() {")
    lines.append("        transmitCalled = false;")
    lines.append("        receiveCalled = false;")
    lines.append("        transmitResult = true;")
    lines.append("        lastTransmitted = CanFrame{};")
    lines.append("        rxQueue.clear();")
    lines.append("    }")
    lines.append("")
    lines.append("    bool transmitCalled = false;")
    lines.append("    bool receiveCalled = false;")
    lines.append("    bool transmitResult = true;")
    lines.append("    CanFrame lastTransmitted{};")
    lines.append("    std::deque<CanFrame> rxQueue;")
    lines.append("};")
    lines.append("")
    lines.append("class MockCanMutex : public ICanMutex {")
    lines.append("public:")
    lines.append("    void lock() override {}")
    lines.append("    void unlock() override {}")
    lines.append("};")
    lines.append("")

    # helpers to create default messages and frames
    for msg in usable:
        struct_name = to_struct_name(msg["name"])
        enum_name = sanitize_name(msg["name"])
        field_name = to_cache_field_name(msg["name"])
        owner = resolve_owner(msg, ownership_config)

        lines.append(f"static {struct_name} makeDefault{struct_name}() {{")
        lines.append(f"    {struct_name} msg{{}};")
        lines.append("    return msg;")
        lines.append("}")
        lines.append("")

        lines.append(f"static CanFrame makeFrame{struct_name}() {{")
        lines.append(f"    {struct_name} msg = makeDefault{struct_name}();")
        lines.append("    CanFrame frame{};")
        lines.append(f"    bool ok = encode{struct_name}(msg, frame);")
        lines.append("    assert(ok);")
        lines.append("    return frame;")
        lines.append("}")
        lines.append("")

        lines.append(f"static void testSendTyped{struct_name}() {{")
        lines.append("    MockCanDriver driver;")
        lines.append("    MockCanMutex mutex;")
        lines.append(f"    CanInterface can(driver, mutex, CanModule::{owner});")
        lines.append(f"    {struct_name} msg = makeDefault{struct_name}();")
        lines.append("    CanError err = can.send(msg);")
        lines.append("    assert(err == CanError::Ok);")
        lines.append("    assert(driver.transmitCalled);")
        lines.append(f"    const MessageDefinition* def = getMessageDefinition(CanMessageTraits<{struct_name}>::id);")
        lines.append("    assert(def != nullptr);")
        lines.append("    assert(driver.lastTransmitted.id == def->canId);")
        lines.append("    assert(driver.lastTransmitted.dlc == def->dlc);")
        lines.append("    assert(driver.lastTransmitted.extended == def->extended);")
        lines.append("}")
        lines.append("")

        lines.append(f"static void testReceiveAnyAndUpdate{struct_name}() {{")
        lines.append("    MockCanDriver driver;")
        lines.append("    MockCanMutex mutex;")
        lines.append(f"    CanInterface can(driver, mutex, CanModule::{owner});")
        lines.append(f"    CanFrame frame = makeFrame{struct_name}();")
        lines.append("    driver.inject(frame);")
        lines.append("    bool ok = can.receiveAnyAndUpdate(0);")
        lines.append("    assert(ok);")
        lines.append(f"    assert(can.snapshot().{field_name}Valid);")
        lines.append("}")
        lines.append("")

        lines.append(f"static void testSendRaw{struct_name}() {{")
        lines.append("    MockCanDriver driver;")
        lines.append("    MockCanMutex mutex;")
        lines.append(f"    CanInterface can(driver, mutex, CanModule::{owner});")
        lines.append(f"    CanFrame frame = makeFrame{struct_name}();")
        lines.append(f"    CanError err = can.sendRaw(CanMessageTraits<{struct_name}>::id, frame);")
        lines.append("    assert(err == CanError::Ok);")
        lines.append("    assert(driver.transmitCalled);")
        lines.append("}")
        lines.append("")

    # mismatch tests pair each message with next
    if len(usable) > 1:
        for i, msg in enumerate(usable):
            other = usable[(i + 1) % len(usable)]
            if other["name"] == msg["name"]:
                continue

            struct_name = to_struct_name(msg["name"])
            other_struct_name = to_struct_name(other["name"])
            field_name = to_cache_field_name(msg["name"])
            owner = resolve_owner(msg, ownership_config)

            lines.append(f"static void testReceiveMismatch{struct_name}() {{")
            lines.append("    MockCanDriver driver;")
            lines.append("    MockCanMutex mutex;")
            lines.append(f"    CanInterface can(driver, mutex, CanModule::{owner});")
            lines.append(f"    CanFrame frame = makeFrame{other_struct_name}();")
            lines.append("    driver.inject(frame);")
            lines.append("    can.receiveAnyAndUpdate(0);")
            lines.append(f"    assert(!can.snapshot().{field_name}Valid);")
            lines.append("}")
            lines.append("")

    lines.append("static void testReceiveAnyAndUpdateUnknownFrame() {")
    lines.append("    MockCanDriver driver;")
    lines.append("    MockCanMutex mutex;")
    lines.append("    CanInterface can(driver, mutex, CanModule::MODULE_UNKNOWN);")
    lines.append("    CanFrame frame{};")
    lines.append("    frame.id = 0x7FFFFFFF;")
    lines.append("    frame.dlc = 8;")
    lines.append("    frame.extended = true;")
    lines.append("    driver.inject(frame);")
    lines.append("    bool ok = can.receiveAnyAndUpdate(0);")
    lines.append("    assert(!ok);")
    lines.append("}")
    lines.append("")

    lines.append("int main() {")
    lines.append('    std::cout << "Running generated interface tests...\\n";')

    count = 0
    for msg in usable:
        struct_name = to_struct_name(msg["name"])
        lines.append(f"    testSendTyped{struct_name}();")
        count += 1
        lines.append(f"    testReceiveAnyAndUpdate{struct_name}();")
        count += 1
        lines.append(f"    testSendRaw{struct_name}();")
        count += 1

    if len(usable) > 1:
        for msg in usable:
            struct_name = to_struct_name(msg["name"])
            lines.append(f"    testReceiveMismatch{struct_name}();")
            count += 1

    lines.append("    testReceiveAnyAndUpdateUnknownFrame();")
    count += 1

    lines.append("")
    lines.append('    std::cout << "All generated interface tests passed.\\n";')
    lines.append(f'    std::cout << "Messages tested: {len(usable)}\\n";')
    lines.append(f'    std::cout << "Interface test blocks run: {count}\\n";')
    lines.append("    return 0;")
    lines.append("}")

    output_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    base_dir = Path(__file__).resolve().parent.parent
    dbc_path = base_dir / "dbc" / "WFR25.dbc"
    config_path = base_dir / "config" / "ownership.yaml"
    output_path = base_dir / "tests" / "generated" / "test_interface_generated.cpp"

    messages = parse_dbc_messages(dbc_path)
    ownership_config = load_ownership_config(config_path)

    generate_interface_test_cpp(messages, ownership_config, output_path)
    print(f"Generated: {output_path}")
    print(f"Usable messages: {len([m for m in messages if not should_skip_message(m)])}")


if __name__ == "__main__":
    main()